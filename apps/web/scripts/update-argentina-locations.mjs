import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const dataPath = resolve(root, 'data/argentina-locations.json')
const seedPath = resolve(root, 'supabase/migrations/20260717000001_seed_argentina_locations.sql')
const source = 'https://apis.datos.gob.ar/georef/api/v2.0'

function assertArray(value, label) {
  if (!Array.isArray(value)) throw new Error(`Georef cambió su estructura: falta el array ${label}.`)
  return value
}

function text(value, label) {
  if (typeof value !== 'string' || !value.trim()) throw new Error(`Georef cambió su estructura: ${label} no es texto válido.`)
  return value.trim()
}

async function fetchDataset(resource, key) {
  const response = await fetch(`${source}/${resource}.json`)
  if (!response.ok) throw new Error(`No se pudo descargar ${resource}: ${response.status} ${response.statusText}`)
  const payload = await response.json()
  return assertArray(payload?.[key], key)
}

function sql(value) {
  return `'${value.replaceAll("'", "''")}'`
}

const [provincesSource, citiesSource] = await Promise.all([
  fetchDataset('provincias', 'provincias'),
  fetchDataset('localidades', 'localidades'),
])

const provinces = new Map()
for (const province of provincesSource) {
  const id = text(province?.id, 'provincias[].id')
  const name = text(province?.nombre, 'provincias[].nombre')
  provinces.set(id, { id, name, cities: [] })
}

if (provinces.size !== 24) throw new Error(`Georef devolvió ${provinces.size} provincias; se esperaban 24.`)

const seenCityIds = new Set()
for (const city of citiesSource) {
  const cityId = text(city?.id, 'localidades[].id')
  const cityName = text(city?.nombre, 'localidades[].nombre')
  const provinceId = text(city?.provincia?.id, 'localidades[].provincia.id')
  const departmentId = text(city?.departamento?.id, 'localidades[].departamento.id')
  const departmentName = text(city?.departamento?.nombre, 'localidades[].departamento.nombre')
  const province = provinces.get(provinceId)

  if (!province) throw new Error(`La localidad ${cityId} referencia la provincia inexistente ${provinceId}.`)
  if (seenCityIds.has(cityId)) continue

  seenCityIds.add(cityId)
  province.cities.push({ id: cityId, name: cityName, departmentId, departmentName })
}

const collator = new Intl.Collator('es-AR', { sensitivity: 'base' })
const locations = [...provinces.values()]
  .map((province) => ({
    ...province,
    cities: province.cities.sort((a, b) => collator.compare(a.name, b.name) || a.id.localeCompare(b.id)),
  }))
  .sort((a, b) => collator.compare(a.name, b.name) || a.id.localeCompare(b.id))

const json = `${JSON.stringify(locations, null, 2)}\n`
const rows = locations.flatMap((province) => province.cities.map((city) =>
  `  ('AR', ${sql(province.id)}, ${sql(province.name)}, ${sql(city.id)}, ${sql(city.name)}, ${sql(city.departmentId)}, ${sql(city.departmentName)})`,
))
const seed = `-- Generated by apps/web/scripts/update-argentina-locations.mjs. Do not edit manually.\ninsert into public.argentina_locations (country_code, province_id, province, city_id, city, department_id, department)\nvalues\n${rows.join(',\n')}\non conflict (city_id) do update\n  set country_code = excluded.country_code,\n      province_id = excluded.province_id,\n      province = excluded.province,\n      city = excluded.city,\n      department_id = excluded.department_id,\n      department = excluded.department;\n`

await mkdir(dirname(dataPath), { recursive: true })
await writeFile(dataPath, json)
await writeFile(seedPath, seed)

console.log(`Georef procesado: ${locations.length} provincias y ${rows.length} localidades.`)
console.log(`JSON: ${dataPath} (${Buffer.byteLength(json)} bytes)`)
console.log(`Seed SQL: ${seedPath}`)
